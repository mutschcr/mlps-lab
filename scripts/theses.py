"""Generate static thesis listings and detail pages (Python 3.11+)."""
import re
import tomllib
import unicodedata
from datetime import date
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/theses"
STATES = ("open", "running", "finished")
GENERATED = "<!-- Generated by scripts/theses.py -->"


def filename(name, title):
    text = (name + " " + title).casefold()
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def read_topic(path):
    with path.open("rb") as stream:
        t = tomllib.load(stream)
    slug = path.stem
    if slug in {"index", "projects"} or not re.fullmatch(r"[a-z0-9]+(?:[-_][a-z0-9]+)*", slug):
        raise ValueError(f"Invalid filename: {path.name}")
    if t.get("status") not in STATES or t.get("type") not in ("Master Thesis", "Bachelor Thesis", "Project", "Thesis"):
        raise ValueError(f"Invalid status or type in {path.name}")
    if not isinstance(t.get("title"), str) or not t["title"].strip():
        raise ValueError(f"Missing title in {path.name}")
    if not isinstance(t.get("tags", []), list) or not all(isinstance(tag, str) for tag in t.get("tags", [])):
        raise ValueError(f"Invalid tags in {path.name}")
    for field in ("posted", "started", "finished"):
        if t.get(field):
            value = str(t[field])
            if not re.fullmatch(r"[0-9]{4}", value):
                date.fromisoformat(value)
                if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
                    raise ValueError(f"Invalid {field} in {path.name}")
            t[field] = value
    owner = t.get("student") or t.get("filename_owner") or "unknown student"
    if slug != filename(owner, t["title"]):
        raise ValueError(f"Expected filename {filename(owner, t['title'])}.toml")
    t["slug"] = t.get("detail_slug", slug)
    if not re.fullmatch(r"[a-z0-9]+(?:[-_][a-z0-9]+)*", t["slug"]):
        raise ValueError(f"Invalid detail slug in {path.name}")
    return t


def labels(t):
    return " ".join(f'<span rel="tag">{escape(tag)}</span>' for tag in t.get("tags", []))


def metadata(t):
    fields = []
    if t["status"] != "open":
        fields.append("Student: " + escape(t.get("student") or "Not recorded"))
    names = []
    for name in t.get("supervisors", []):
        profile = filename(name, "")
        href = "../team/" + profile + "/"
        names.append(f'<a href="{href}">{escape(name)}</a>' if (OUT / href / "index.html").is_file() else escape(name))
    fields.append("Supervisor: " + (", ".join(names) or "Not recorded"))
    if t.get("institution"):
        fields.append(escape(t["institution"]))
    field = {"open": "posted", "running": "started", "finished": "finished"}[t["status"]]
    fields.append(field.title() + ": " + escape(t.get(field) or "Not recorded"))
    return " · ".join(fields)


def card(t):
    url = t["slug"] + ".html"
    title = escape(t["title"])
    image_path = t.get("image") or "../assets/media/theses/no-image.jpg"
    image_class = "" if t.get("image") else ' class="thesis-placeholder"'
    image = f'<div class="column"><figure class="entry-image"><a href="{url}" aria-label="{title}"><img src="{escape(image_path)}"{image_class} alt="" loading="lazy"></a></figure></div>'
    return f'''<li class="wp-block-post"><div class="columns">{image}<div class="column">
<div class="taxonomy-category"><span class="thesis-type" rel="tag">{escape(t["type"])}</span></div>
<h2 class="entry-heading"><a href="{url}">{title}</a></h2>
<div class="entry-excerpt"><p>{escape(t.get("summary", ""))}</p></div>
<div class="taxonomy-post_tag">{labels(t)}</div>
<div class="wp-block-group is-layout-flex row-between"><span>{metadata(t)}</span><a class="read-more" href="{url}">View topic →</a></div>
</div></div></li>'''


def overview_name(state, page=1):
    if state == "open":
        return "index.html"
    return f"{state}.html" if page == 1 else f"{state}-{page}.html"


def catalog(topics, state, rows, page, total):
    controls = []
    for option in STATES:
        count = sum(t["status"] == option for t in topics)
        current = ' aria-current="page"' if state == option else ""
        controls.append(f'<a href="{overview_name(option)}"{current}>{option.title()} ({count})</a>')
    nav = '<nav class="thesis-status" aria-label="Thesis status">' + " ".join(controls) + "</nav>"
    content = ('<ul class="entry-list">' + "\n".join(map(card, rows)) + "</ul>") if rows else f"<p>No {state} topics at present.</p>"
    pager = ""
    if total > 1:
        numbers = []
        for n in range(1, total + 1):
            current = ' aria-current="page"' if n == page else ""
            numbers.append(f'<a href="{overview_name(state, n)}"{current} aria-label="Page {n}">{n}</a>')
        pager = '<nav class="thesis-pages" aria-label="Finished topics pages">' + " ".join(numbers) + "</nav>"
    return nav + '<section class="mlps-thesis-list">' + content + "</section>" + pager


def main():
    topics = [read_topic(p) for p in sorted((ROOT / "data/theses").glob("*.toml"))]
    templates = ROOT / "templates"
    index = (templates / "theses-index.html").read_text(encoding="utf-8")
    detail = (templates / "thesis-detail.html").read_text(encoding="utf-8")
    pages = {}
    for state in STATES:
        rows = sorted((t for t in topics if t["status"] == state), key=lambda t: t["title"].casefold())
        if state == "finished":
            rows.sort(key=lambda t: t.get("finished", ""), reverse=True)
        size = 10 if state == "finished" else max(1, len(rows))
        total = max(1, (len(rows) + size - 1) // size)
        for page in range(1, total + 1):
            name = overview_name(state, page)
            markup = catalog(topics, state, rows[(page - 1)*size:page*size], page, total)
            result = index.replace("<!-- thesis:catalog -->", markup)
            result = result.replace("<title>", f"<title>{state.title()} · ", 1)
            if name != "index.html":
                result = result.replace('rel="canonical" href="https://mlps-lab.de/theses/"', f'rel="canonical" href="https://mlps-lab.de/theses/{name}"')
            pages[name] = result
    pages["projects.html"] = '<!doctype html><html lang="en"><head><title>Theses and Projects</title><meta http-equiv="refresh" content="0;url=./"></head><body><a href="./">Theses and Projects</a></body></html>'
    for t in topics:
        if t["slug"] + ".html" in pages:
            raise ValueError(f"Duplicate or reserved route: {t['slug']}")
        title = escape(t["title"])
        article = f'''<article class="sinatra-article"><div class="post-category"><span rel="tag">{escape(t["type"])}</span> <span rel="tag">{t["status"].title()}</span></div>
<header class="entry-header"><h1 class="entry-title">{title}</h1><p>{metadata(t)}</p></header>
<div class="entry-content si-entry">{t.get("body_html") or escape(t.get("summary", ""))}</div>
<div class="entry-footer"><div class="post-tags"><span class="cat-links">{labels(t)}</span></div></div></article>'''
        pages[t["slug"] + ".html"] = detail.replace("<!-- thesis:title -->", title).replace("<!-- thesis:slug -->", t["slug"]).replace("<!-- thesis:article -->", article)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, page in pages.items():
        path = OUT / name
        content = page.replace("</head>", GENERATED + "\n</head>", 1)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            tmp = path.with_suffix(".html.tmp")
            tmp.write_text(content, encoding="utf-8")
            tmp.replace(path)
    for path in OUT.glob("*.html"):
        if path.name not in pages and GENERATED in path.read_text(encoding="utf-8"):
            path.unlink()
    print(f"{len(topics)} topics, {len(pages)} pages")


if __name__ == "__main__":
    main()
